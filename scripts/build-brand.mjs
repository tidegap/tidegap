#!/usr/bin/env node
// Generate every Tidegap brand vector and snippet from two sources:
//   - the wave geometry constants below (measured on the chosen reference
//     raster, see docs/brand.md), and
//   - the vendored Poppins Medium font (assets/brand/fonts/), outlined to
//     paths with opentype.js, so no output depends on an installed font.
//
// Outputs (all committed; scripts/render-images.mjs runs this before rendering):
//   assets/brand/tidegap-logo-dark.svg    stacked lockup for dark backgrounds
//   assets/brand/tidegap-logo-light.svg   stacked lockup for light backgrounds
//   assets/brand/tidegap-mark.svg         heavy wave, 64x64, transparent
//   assets/brand/tidegap-icon.svg         heavy wave on a full-bleed navy tile
//   apps/web/public/icon.svg              copy of tidegap-icon.svg
//   apps/web/src/lib/brand.generated.ts   palette + horizontal header form
//   packages/cli/ui/index.html            the block between the brand-mark markers
//
// Deterministic: fixed attribute order, numbers rounded to 2 decimals, LF
// endings. Two runs give identical bytes. scripts/check-images.mjs pins the
// outputs through the brand block of assets/images.lock.json.

import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import opentype from "opentype.js";
import { BRAND, ROOT } from "./check-images.mjs";

// Palette sampled from the reference raster (mode of each region).
const NAVY = "#0C1017";
const WHITE = "#FFFFFF";
const OFF_WHITE = "#FAFAFA";
const TEAL = "#5FC6C4";

// Wave geometry in reference pixels. Each half-period is a crest arc, a
// straight tangent segment at SLOPE_DEG and a trough arc of the same radius.
const PERIOD = 257;
const AMPLITUDE = 51.5; // centreline, midline to crest
const SLOPE_DEG = 56;
const STROKE_LOCKUP = 20; // stroke / period ~ 0.078, as in the reference
const STROKE_HEAVY = 46; // stroke / period ~ 0.18, for the mark and the icon

// Lockup layout, as fractions of the wave's outer width.
const WORDMARK_WIDTH = 1.022;
const WORDMARK_GAP = 0.0916; // wave bottom to cap top
const TRACKING_EM = -0.025; // space added between glyphs, in em (negative: tighter)

// Horizontal header form, as fractions of the wordmark cap height.
const HEADER_MARK_HEIGHT = 1.3;
const HEADER_GAP = 0.5;

const WORDMARK_TEXT = "Tidegap";
const HEADER = "<!-- Generated by scripts/build-brand.mjs. Do not edit. -->";

const r2 = (n) => {
  const v = Math.round(n * 100) / 100;
  return Object.is(v, -0) ? "0" : String(v);
};

// ---- wave -----------------------------------------------------------------

// The wave in unit space: midline y = 0, trough centre x = 0, crests at
// x = -P/2 and +P/2. Returns path data scaled by k and offset by (ox, oy).
function wave({ stroke, k = 1, ox = 0, oy = 0, periods = 2 }) {
  const theta = (SLOPE_DEG * Math.PI) / 180;
  const h = PERIOD / 2;
  const a = AMPLITUDE;
  // Radius that makes the tangent segment pass through the midline crossing.
  const r = (Math.tan(theta) * (h / 2) - a) / (1 / Math.cos(theta) - 1);
  const dx = r * Math.sin(theta);
  const dy = r * (1 - Math.cos(theta));
  if (dx >= h / 2 || r - stroke / 2 <= 0) throw new Error("build-brand: wave constants do not fit");

  const X = (x) => r2(ox + k * x);
  const Y = (y) => r2(oy + k * y);
  const R = r2(k * r);
  // Path from the trough left of the first crest to the trough right of the
  // second one: two periods (more for the animated header), later clipped at
  // the midline.
  const parts = [];
  let x = -PERIOD;
  parts.push(`M${X(x)} ${Y(a)}`);
  for (let i = 0; i < 2 * periods; i++) {
    const up = i % 2 === 0; // trough -> crest, else crest -> trough
    const s = up ? -1 : 1; // direction of y travel
    const y0 = up ? a : -a;
    // leaving arc, tangent segment, arriving arc
    parts.push(`A${R} ${R} 0 0 ${up ? 0 : 1} ${X(x + dx)} ${Y(y0 + s * dy)}`);
    parts.push(`L${X(x + h - dx)} ${Y(-y0 - s * dy)}`);
    parts.push(`A${R} ${R} 0 0 ${up ? 1 : 0} ${X(x + h)} ${Y(-y0)}`);
    x += h;
  }

  const halfCut = stroke / 2 / Math.sin(theta); // half the stroke width along the midline
  const outer = 1.5 * h + halfCut; // outer half-width after the midline cut
  const top = -a - stroke / 2;
  const bottom = a + stroke / 2;
  const box = (x0, y0, x1, y1) => ({ x: r2(ox + k * x0), y: r2(oy + k * y0), width: r2(k * (x1 - x0)), height: r2(k * (y1 - y0)) });
  return {
    d: parts.join(""),
    stroke: r2(k * stroke),
    period: r2(k * PERIOD),
    // ink: everything above the midline (cuts both outer arms flat)
    inkClip: box(-outer - 1, top - 1, outer + 1, 0),
    // teal: everything at or below the midline between the crest centres
    tealClip: box(-h, -0.5 / k, h, bottom + 1),
    width: 2 * outer,
    height: bottom - top,
    top,
  };
}

function waveSvg(w, id, ink, teal) {
  return [
    `<defs><clipPath id="${id}-ink"><rect x="${w.inkClip.x}" y="${w.inkClip.y}" width="${w.inkClip.width}" height="${w.inkClip.height}"/></clipPath>`,
    `<clipPath id="${id}-teal"><rect x="${w.tealClip.x}" y="${w.tealClip.y}" width="${w.tealClip.width}" height="${w.tealClip.height}"/></clipPath></defs>`,
    `<path class="ink" d="${w.d}" fill="none" stroke="${ink}" stroke-width="${w.stroke}" clip-path="url(#${id}-ink)"/>`,
    `<path d="${w.d}" fill="none" stroke="${teal}" stroke-width="${w.stroke}" clip-path="url(#${id}-teal)"/>`,
  ].join("\n");
}

// ---- wordmark -------------------------------------------------------------

const font = opentype.loadSync(join(ROOT, BRAND.font));
const CAP = font.tables.os2.sCapHeight / font.unitsPerEm; // in em

// Lay the glyphs one by one at 1 unit per em, baseline y = 0.
function layoutWordmark() {
  const glyphs = font.stringToGlyphs(WORDMARK_TEXT);
  const commands = [];
  let x = 0;
  glyphs.forEach((glyph, i) => {
    commands.push(...glyph.getPath(x, 0, 1).commands);
    x += glyph.advanceWidth / font.unitsPerEm + TRACKING_EM;
    const next = glyphs[i + 1];
    if (next) x += font.getKerningValue(glyph, next) / font.unitsPerEm;
  });
  const xs = commands.flatMap((c) => [c.x, c.x1, c.x2].filter((v) => v !== undefined));
  const ys = commands.flatMap((c) => [c.y, c.y1, c.y2].filter((v) => v !== undefined));
  return { commands, minX: Math.min(...xs), maxX: Math.max(...xs), minY: Math.min(...ys), maxY: Math.max(...ys) };
}

const WORD = layoutWordmark();

// Path data for the wordmark scaled so it is `width` wide, its left edge at
// x0 and its baseline at y0.
function wordmark(width, x0, y0) {
  const k = width / (WORD.maxX - WORD.minX);
  const X = (x) => r2(x0 + k * (x - WORD.minX));
  const Y = (y) => r2(y0 + k * y);
  const d = WORD.commands
    .map((c) => {
      switch (c.type) {
        case "M": return `M${X(c.x)} ${Y(c.y)}`;
        case "L": return `L${X(c.x)} ${Y(c.y)}`;
        case "Q": return `Q${X(c.x1)} ${Y(c.y1)} ${X(c.x)} ${Y(c.y)}`;
        case "C": return `C${X(c.x1)} ${Y(c.y1)} ${X(c.x2)} ${Y(c.y2)} ${X(c.x)} ${Y(c.y)}`;
        case "Z": return "Z";
        default: throw new Error(`build-brand: unknown path command ${c.type}`);
      }
    })
    .join("");
  return { d, ascent: -k * WORD.minY, descent: k * WORD.maxY };
}

// ---- outputs --------------------------------------------------------------

function lockup(id, ink, teal) {
  const w = wave({ stroke: STROKE_LOCKUP });
  const width = w.width * WORDMARK_WIDTH;
  const k = width / (WORD.maxX - WORD.minX);
  const baseline = w.top + w.height + w.width * WORDMARK_GAP + k * CAP;
  const word = wordmark(width, -width / 2, baseline);
  const minX = Math.floor(-width / 2);
  const minY = Math.floor(w.top);
  const vw = Math.ceil(width / 2) - minX;
  const vh = Math.ceil(baseline + word.descent) - minY;
  return [
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${minX} ${minY} ${vw} ${vh}" width="${vw}" height="${vh}" role="img" aria-label="Tidegap">`,
    HEADER,
    waveSvg(w, id, ink, teal),
    `<path d="${word.d}" fill="${ink}"/>`,
    "</svg>",
    "",
  ].join("\n");
}

// The heavy wave scaled to `size` wide, centred on (cx, cy).
function heavyWave(size, cx, cy) {
  const unit = wave({ stroke: STROKE_HEAVY });
  const k = size / unit.width;
  return wave({ stroke: STROKE_HEAVY, k, ox: cx, oy: cy - k * (unit.top + unit.height / 2) });
}

// A 64x64 tile: the shared root, the generated-file header, then `parts`.
function tileSvg(...parts) {
  return [
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64" width="64" height="64" role="img" aria-label="Tidegap">`,
    HEADER,
    ...parts,
    "</svg>",
    "",
  ].join("\n");
}

function markSvg() {
  return tileSvg(
    `<style>@media (prefers-color-scheme: dark) { .ink { stroke: ${WHITE}; } }</style>`,
    waveSvg(heavyWave(52, 32, 32), "tg-mark", NAVY, TEAL),
  );
}

function iconSvg() {
  return tileSvg(`<rect width="64" height="64" fill="${NAVY}"/>`, waveSvg(heavyWave(48, 32, 32), "tg-icon", WHITE, TEAL));
}

// Horizontal header form for the site: heavy mark left, wordmark right.
function headerForm() {
  const capHeight = 100; // design units; the viewBox scales it
  const unit = wave({ stroke: STROKE_HEAVY });
  const k = (HEADER_MARK_HEIGHT * capHeight) / unit.height;
  const markWidth = k * unit.width;
  // Three periods so the site can slide the path one period inside fixed clips.
  const mark = wave({ stroke: STROKE_HEAVY, k, ox: markWidth / 2, oy: -capHeight / 2 - k * (unit.top + unit.height / 2), periods: 3 });
  const wordWidth = (capHeight / CAP) * (WORD.maxX - WORD.minX);
  const word = wordmark(wordWidth, markWidth + HEADER_GAP * capHeight, 0);
  const minY = Math.floor(Math.min(-capHeight / 2 - (k * unit.height) / 2, -word.ascent));
  const width = Math.ceil(markWidth + HEADER_GAP * capHeight + wordWidth);
  const height = Math.ceil(Math.max(word.descent, -capHeight / 2 + (k * unit.height) / 2)) - minY;
  return { viewBox: `0 ${minY} ${width} ${height}`, mark, wordmark: word.d };
}

function brandModule() {
  const h = headerForm();
  const clip = (c) => `{ x: ${c.x}, y: ${c.y}, width: ${c.width}, height: ${c.height} }`;
  return `// GENERATED by scripts/build-brand.mjs — DO NOT EDIT.
// Run \`pnpm gen:images\` (or \`pnpm gen:brand\`) to regenerate.

export const BRAND_PALETTE = {
  navy: "${NAVY}",
  white: "${WHITE}",
  offWhite: "${OFF_WHITE}",
  teal: "${TEAL}",
} as const;

/** Horizontal header form: heavy wave left, outlined wordmark right. */
export const BRAND_HEADER = {
  viewBox: "${h.viewBox}",
  stroke: ${h.mark.stroke},
  wave: "${h.mark.d}",
  wavePeriod: ${h.mark.period},
  inkClip: ${clip(h.mark.inkClip)},
  tealClip: ${clip(h.mark.tealClip)},
  wordmark: "${h.wordmark}",
} as const;
`;
}

// Inline mark for the `tidegap ui` header: tight viewBox, no xmlns (the UI
// test bans http URLs in index.html), no style attribute (the UI CSP has no
// style-src); the ink follows the CSS colour through currentColor.
function uiBlock() {
  const unit = wave({ stroke: STROKE_HEAVY });
  const k = 32 / unit.width;
  const w = wave({ stroke: STROKE_HEAVY, k, ox: 16, oy: -k * unit.top });
  const height = Math.ceil(k * unit.height);
  return (
    `<svg class="brand-mark" viewBox="0 0 32 ${height}" aria-hidden="true" focusable="false">` +
    waveSvg(w, "tg-ui", "currentColor", TEAL).replaceAll("\n", "") +
    "</svg>"
  );
}

function writeUiBlock() {
  const path = join(ROOT, BRAND.uiHtml);
  const html = readFileSync(path, "utf8");
  const start = html.indexOf(BRAND.uiStart);
  const end = html.indexOf(BRAND.uiEnd);
  if (start < 0 || end < start) {
    console.error(`build-brand: ${BRAND.uiHtml} lacks the ${BRAND.uiStart} / ${BRAND.uiEnd} markers`);
    process.exit(1);
  }
  const next = html.slice(0, start + BRAND.uiStart.length) + uiBlock() + html.slice(end);
  writeFileSync(path, next);
}

const icon = iconSvg();
const files = {
  [BRAND.svgs.logoDark]: lockup("tg-logo-dark", WHITE, TEAL),
  [BRAND.svgs.logoLight]: lockup("tg-logo-light", NAVY, TEAL),
  [BRAND.svgs.mark]: markSvg(),
  [BRAND.svgs.icon]: icon,
  [BRAND.svgs.webIcon]: icon,
  [BRAND.module]: brandModule(),
};
for (const [path, text] of Object.entries(files)) {
  writeFileSync(join(ROOT, path), text);
  console.log(`${path}  ${Buffer.byteLength(text)} bytes`);
}
writeUiBlock();
console.log(`${BRAND.uiHtml}  brand-mark block written`);
